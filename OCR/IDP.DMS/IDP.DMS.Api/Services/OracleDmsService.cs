        var engine = NormalizeOcrEngine(request.Engine);
        var extractedText = !string.IsNullOrWhiteSpace(request.ExtractedText)
            ? request.ExtractedText.Trim()
            : document.Description?.Trim();
        if (string.IsNullOrWhiteSpace(extractedText))
        {
            throw new BusinessRuleException("Tài liệu chưa có nội dung OCR thật. Vui lòng upload/chạy OCR file trước khi bóc tách metadata.");
        }

        var previousStatus = string.IsNullOrWhiteSpace(document.OcrStatus) ? "PENDING" : document.OcrStatus;
        await CreateDocumentVersionAsync(documentId, new DocumentVersionRequest(
            string.IsNullOrWhiteSpace(request.Actor) ? "system" : request.Actor,
            "Lưu phiên bản trước khi xử lý OCR"));
        await UpdateDocumentOcrAsync(documentId, "DONE", TrimText(extractedText, 1000));
        await InsertWorkflowEventAsync("DOCUMENT", documentId, "OCR_PROCESS", previousStatus, "DONE", request.Note, request.Actor, request.UnitCode);

        return new Gd2OcrResultDto(
            document.Id,
            document.Code,
            document.Title,
            engine,
            previousStatus,
            "DONE",
            CalculateOcrConfidence(document, engine),
            extractedText,
            DateTime.Now);
    }

