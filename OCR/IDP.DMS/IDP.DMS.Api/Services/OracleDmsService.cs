            {
                jobCommand.Transaction = transaction;
                var id = new OracleParameter("id", OracleDbType.Int64, ParameterDirection.Output);
                jobCommand.Parameters.Add(id);
                await jobCommand.ExecuteNonQueryAsync();
                jobId = Convert.ToInt64(id.Value.ToString());
            }

            foreach (var row in rows)
            {
                var hasError = validationErrors.TryGetValue(row.RowNumber, out var error);
                await using var itemCommand = BuildCommand(connection, """
                    INSERT INTO DMS_BATCH_IMPORT_ITEMS
                        (JOB_ID, ROW_NUMBER, DOSSIER_CODE, DOCUMENT_CODE, ATTACHMENT_FILE_NAME,
                         STATUS, MESSAGE, OCR_ENGINE)
                    VALUES
                        (:jobId, :rowNumber, :dossierCode, :documentCode, :attachment,
                         :status, :message, :ocrEngine)
                    """,
                    P("jobId", jobId), P("rowNumber", row.RowNumber), P("dossierCode", row.DossierCode),
                    P("documentCode", row.DocumentCode), P("attachment", row.AttachmentFileName),
                    P("status", hasError ? "VALIDATION_ERROR" : "VALIDATED"), P("message", error),
                    P("ocrEngine", engine));
                itemCommand.Transaction = transaction;
                await itemCommand.ExecuteNonQueryAsync();
            }

            await using (var statusCommand = BuildCommand(connection,
                "UPDATE DMS_BATCH_IMPORT_JOBS SET STATUS='VALIDATED' WHERE ID=:id", P("id", jobId)))
            {
                statusCommand.Transaction = transaction;
                await statusCommand.ExecuteNonQueryAsync();
            }
            await transaction.CommitAsync();
            return jobId;
        }
        catch
        {
            await transaction.RollbackAsync();
            throw;
        }
    }

    public async Task<IReadOnlyList<BatchOcrQueueItem>> ImportBatchDossierAsync(
        long jobId,
        BatchImportDossierInput input,
        string engine)
    {
        await using var connection = CreateConnection();
        await connection.OpenAsync();
        await using var transaction = (OracleTransaction)await connection.BeginTransactionAsync();
        try
        {
            long storageId;
            await using (var storageCommand = BuildCommand(connection, """
                SELECT ID FROM DMS_STORAGE_LOCATIONS
                WHERE UPPER(CODE)=UPPER(:code) AND UPPER(NVL(STATUS, 'ACTIVE'))='ACTIVE'
                """, P("code", input.StorageCode)))
            {
                storageCommand.Transaction = transaction;
                var value = await storageCommand.ExecuteScalarAsync();
                if (value is null || value == DBNull.Value)
                    throw new BusinessRuleException($"Mã kho '{input.StorageCode}' không tồn tại hoặc chưa hoạt động.");
                storageId = Convert.ToInt64(value);
            }

            await using (var duplicateCommand = BuildCommand(connection, """
                SELECT COUNT(*) FROM DMS_DOSSIERS WHERE UPPER(CODE)=UPPER(:code)
                """, P("code", input.DossierCode)))
            {
                duplicateCommand.Transaction = transaction;
                if (Convert.ToInt64(await duplicateCommand.ExecuteScalarAsync()) > 0)
                    throw new BusinessRuleException($"Mã hồ sơ '{input.DossierCode}' đã tồn tại.");
            }

            long dossierId;
            await using (var dossierCommand = BuildCommand(connection, """
                INSERT INTO DMS_DOSSIERS
                    (CODE, TITLE, DOSSIER_TYPE, STORAGE_ID, STATUS, DESCRIPTION)
                VALUES
                    (:code, :title, :dossierType, :storageId, 'DRAFT', :description)
                RETURNING ID INTO :id
                """,
                P("code", input.DossierCode), P("title", input.DossierTitle),
                P("dossierType", input.DossierType), P("storageId", storageId),
                P("description", $"Import hàng loạt từ job #{jobId}")))
            {
                dossierCommand.Transaction = transaction;
                var id = new OracleParameter("id", OracleDbType.Int64, ParameterDirection.Output);
                dossierCommand.Parameters.Add(id);
                await dossierCommand.ExecuteNonQueryAsync();
                dossierId = Convert.ToInt64(id.Value.ToString());
            }

            var queueItems = new List<BatchOcrQueueItem>();
            foreach (var document in input.Documents)
            {
                await using (var duplicateDocumentCommand = BuildCommand(connection,
                    "SELECT COUNT(*) FROM DMS_DOCUMENTS WHERE UPPER(CODE)=UPPER(:code)",
                    P("code", document.DocumentCode)))
                {
                    duplicateDocumentCommand.Transaction = transaction;
                    if (Convert.ToInt64(await duplicateDocumentCommand.ExecuteScalarAsync()) > 0)
                        throw new BusinessRuleException($"Mã văn bản '{document.DocumentCode}' đã tồn tại.");
                }

                long documentId;
                await using (var documentCommand = BuildCommand(connection, """
                    INSERT INTO DMS_DOCUMENTS
                        (DOSSIER_ID, CODE, TITLE, FILE_NAME, OCR_STATUS, STATUS, DESCRIPTION)
                    VALUES
                        (:dossierId, :code, :title, :fileName, 'QUEUED', 'DRAFT', NULL)
                    RETURNING ID INTO :id
                    """,
                    P("dossierId", dossierId), P("code", document.DocumentCode),
                    P("title", document.DocumentTitle), P("fileName", document.StoredFileName)))
                {
                    documentCommand.Transaction = transaction;
                    var id = new OracleParameter("id", OracleDbType.Int64, ParameterDirection.Output);
                    documentCommand.Parameters.Add(id);
                    await documentCommand.ExecuteNonQueryAsync();
                    documentId = Convert.ToInt64(id.Value.ToString());
                }

                long itemId;
                await using (var itemCommand = BuildCommand(connection, """
                    SELECT ID FROM DMS_BATCH_IMPORT_ITEMS
                    WHERE JOB_ID=:jobId AND ROW_NUMBER=:rowNumber
                    FOR UPDATE
                    """, P("jobId", jobId), P("rowNumber", document.RowNumber)))
                {
                    itemCommand.Transaction = transaction;
                    var value = await itemCommand.ExecuteScalarAsync();
                    if (value is null || value == DBNull.Value)
                        throw new InvalidOperationException($"Không tìm thấy dòng import {document.RowNumber}.");
                    itemId = Convert.ToInt64(value);
                }

                await using (var updateItemCommand = BuildCommand(connection, """
                    UPDATE DMS_BATCH_IMPORT_ITEMS
                    SET STATUS='OCR_QUEUED', MESSAGE='Đã import, đang chờ OCR',
                        DOSSIER_ID=:dossierId, DOCUMENT_ID=:documentId, STORED_FILE_NAME=:storedFileName,
                        OCR_ENGINE=:ocrEngine, UPDATED_AT=SYSDATE
                    WHERE ID=:id
                    """,
                    P("dossierId", dossierId), P("documentId", documentId),
                    P("storedFileName", document.StoredFileName), P("ocrEngine", engine), P("id", itemId)))
                {
                    updateItemCommand.Transaction = transaction;
                    await updateItemCommand.ExecuteNonQueryAsync();
                }
                queueItems.Add(new BatchOcrQueueItem(jobId, itemId, documentId, document.StoredFileName, engine));
            }

            await transaction.CommitAsync();
            return queueItems;
        }
        catch
        {
            await transaction.RollbackAsync();
            throw;
        }
    }

