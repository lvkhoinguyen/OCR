    private static async Task ExecuteDdlAsync(OracleConnection connection, string sql)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = sql;
        try
        {
            await command.ExecuteNonQueryAsync();
        }
        catch (OracleException ex) when (ex.Number is 955 or 1430)
        {
            // ORA-00955: object/index exists; ORA-01430: column already exists.
        }
    }

    private async Task<IReadOnlyList<T>> QueryAsync<T>(string sql, Func<OracleDataReader, T> map, params OracleParameter[] parameters)
    {
        var results = new List<T>();
        await using var connection = CreateConnection();
        await connection.OpenAsync();
        await using var command = BuildCommand(connection, sql, parameters);
        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync())
        {
            results.Add(map(reader));
        }
        return results;
    }

    private async Task<T?> QuerySingleAsync<T>(string sql, Func<OracleDataReader, T> map, params OracleParameter[] parameters)
    {
        var results = await QueryAsync(sql, map, parameters);
        return results.FirstOrDefault();
    }

    private async Task<int> ExecuteAsync(string sql, params OracleParameter[] parameters)
