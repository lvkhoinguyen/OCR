    private static decimal CalculateOcrConfidence(DocumentDto document, string engine)
    {
        var baseScore = engine switch
        {
            "GEMINI" => 96m,
            "VIETOCR" => 93m,
            "EASYOCR" => 90m,
            "CRNN" => 86m,
            _ => 88m
        };
        if (string.IsNullOrWhiteSpace(document.FileName)) baseScore -= 4m;
        return Math.Clamp(baseScore, 70m, 99m);
    }

    private static Gd2OcrExtractionDto BuildOcrExtraction(DocumentDto document, string engine, string rawText, decimal confidence, bool confirmed)
    {
        var documentType = DetectOcrDocumentType(document, rawText);
        var fields = BuildOcrFields(rawText, documentType, confidence, confirmed);
        var overallConfidence = fields.Count == 0 ? 0 : Math.Round(fields.Average(item => item.Confidence), 2);
        return new Gd2OcrExtractionDto(
            document.Id,
            document.Code,
            document.Title,
            document.FileName ?? $"{document.Code}.pdf",
            documentType,
            overallConfidence,
            fields,
            rawText,
            confirmed ? "CONFIRMED" : "EXTRACTED",
            DateTime.Now);
    }

    private static string DetectOcrDocumentType(DocumentDto document, string? rawText = null)
    {
        var source = $"{document.Title} {document.FileName} {document.Description} {rawText}".ToUpperInvariant();
        if (ContainsAny(source, "HOA DON", "HÓA ĐƠN", "HOÁ ĐƠN", "INVOICE", "MÃ SỐ THUẾ", "MST")) return "INVOICE";
        if (ContainsAny(source, "HOP DONG", "HỢP ĐỒNG", "CONTRACT", "BÊN A", "BÊN B")) return "CONTRACT";
        if (ContainsAny(source, "QUYET DINH", "QUYẾT ĐỊNH", "SỐ QĐ", "QD-")) return "DECISION";
        if (ContainsAny(source, "BAO CAO", "BÁO CÁO", "SỐ BC", "BC-")) return "REPORT";
        return "TEXT";
    }

    private static IReadOnlyList<Gd2OcrFieldDto> BuildOcrFields(string rawText, string documentType, decimal baseConfidence, bool confirmed)
    {
        var fields = new List<Gd2OcrFieldDto>();
        void Add(string key, string label, string value, decimal confidence, int index)
        {
            if (!string.IsNullOrWhiteSpace(value))
            {
                fields.Add(new Gd2OcrFieldDto(key, label, value.Trim(), Math.Clamp(Math.Round(confidence, 2), 50m, 99m), BoxForIndex(index), confirmed));
            }
        }

        if (documentType == "INVOICE")
        {
            Add("invoiceNo", "Số hóa đơn", ExtractOcrValue(rawText, ["Số hóa đơn", "Số HD", "Hóa đơn số"]), baseConfidence, fields.Count);
            Add("seller", "Đơn vị bán", ExtractOcrValue(rawText, ["Đơn vị bán", "Người bán", "Bên bán", "Công ty"]), baseConfidence - 3, fields.Count);
            Add("taxCode", "Mã số thuế", ExtractOcrValue(rawText, ["Mã số thuế", "MST", "Tax code"]), baseConfidence - 8, fields.Count);
            Add("totalAmount", "Tổng tiền", ExtractOcrValue(rawText, ["Tổng tiền", "Thành tiền", "Số tiền", "Cộng tiền"]), baseConfidence - 1, fields.Count);
        }
        else if (documentType == "CONTRACT")
        {
            Add("contractNo", "Số hợp đồng", ExtractOcrValue(rawText, ["Số hợp đồng", "Hợp đồng số", "Số HĐ"]), baseConfidence, fields.Count);
            Add("partyA", "Bên A", ExtractOcrValue(rawText, ["Bên A", "Đại diện bên A"]), baseConfidence - 2, fields.Count);
            Add("partyB", "Bên B", ExtractOcrValue(rawText, ["Bên B", "Đại diện bên B"]), baseConfidence - 8, fields.Count);
            Add("effectiveDate", "Ngày hiệu lực", ExtractOcrValue(rawText, ["Ngày hiệu lực", "Hiệu lực từ", "Ngày ký"]), baseConfidence - 4, fields.Count);
        }
        else if (documentType == "DECISION")
        {
            Add("decisionNo", "Số quyết định", ExtractOcrValue(rawText, ["Số quyết định", "Quyết định số", "Số QĐ"]), baseConfidence, fields.Count);
            Add("issuer", "Cơ quan ban hành", ExtractOcrValue(rawText, ["Cơ quan ban hành", "Đơn vị ban hành", "Nơi ban hành"]), baseConfidence - 2, fields.Count);
            Add("subject", "Trích yếu", ExtractOcrValue(rawText, ["Trích yếu", "Về việc", "Nội dung"]), baseConfidence - 8, fields.Count);
            Add("signedDate", "Ngày ký", ExtractOcrValue(rawText, ["Ngày ký", "Ký ngày", "Ban hành ngày"]), baseConfidence - 3, fields.Count);
        }
        else if (documentType == "REPORT")
        {
            Add("reportNo", "Số báo cáo", ExtractOcrValue(rawText, ["Số báo cáo", "Báo cáo số", "Số BC"]), baseConfidence, fields.Count);
            Add("period", "Kỳ báo cáo", ExtractOcrValue(rawText, ["Kỳ báo cáo", "Tháng", "Quý", "Năm"], keepLineWhenNoSeparator: true), baseConfidence - 5, fields.Count);
            Add("indicator", "Chỉ tiêu chính", ExtractOcrValue(rawText, ["Chỉ tiêu chính", "Chỉ tiêu", "Nội dung", "Kết quả"]), baseConfidence - 8, fields.Count);
            Add("approvedBy", "Người phê duyệt", ExtractOcrValue(rawText, ["Người phê duyệt", "Phê duyệt", "Người ký", "Ký bởi"]), baseConfidence - 2, fields.Count);
        }

        if (fields.Count > 0) return fields;

        return rawText
            .Replace("\r\n", "\n")
            .Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Take(10)
            .Select((line, index) => new Gd2OcrFieldDto($"line_{index + 1}", $"Dòng {index + 1}", line, Math.Clamp(baseConfidence - index, 50m, 99m), BoxForIndex(index), confirmed))
            .ToList();
    }

    private static Gd2OcrBoundingBoxDto BoxForIndex(int index) =>
        new(1, 10, 14 + index * 8, 76, 6);

    private static string ExtractOcrValue(string rawText, IReadOnlyList<string> labels, bool keepLineWhenNoSeparator = false)
    {
        if (string.IsNullOrWhiteSpace(rawText)) return "";
        var lines = rawText.Replace("\r\n", "\n").Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        foreach (var line in lines)
        {
            foreach (var label in labels)
            {
                var match = System.Text.RegularExpressions.Regex.Match(
                    line,
                    $@"\b{System.Text.RegularExpressions.Regex.Escape(label)}\b\s*(?<sep>[:：\-–—]\s*)?(?<value>.+)$",
                    System.Text.RegularExpressions.RegexOptions.IgnoreCase | System.Text.RegularExpressions.RegexOptions.CultureInvariant);
                if (!match.Success) continue;
                var hasSeparator = match.Groups["sep"].Success && !string.IsNullOrWhiteSpace(match.Groups["sep"].Value);
                var value = CleanOcrValue(keepLineWhenNoSeparator && !hasSeparator ? line : match.Groups["value"].Value);
                if (!string.IsNullOrWhiteSpace(value) && !labels.Any(item => string.Equals(item, value, StringComparison.OrdinalIgnoreCase))) return value;
            }
        }
        return "";
    }

    private static bool ContainsAny(string source, params string[] values) =>
