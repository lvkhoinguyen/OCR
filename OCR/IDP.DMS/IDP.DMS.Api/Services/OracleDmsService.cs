    public async Task<Gd2OcrConfirmationResult> ConfirmOcrExtractionAsync(long documentId, Gd2OcrConfirmationRequest request)
    {
        if (request is null) throw new BusinessRuleException("Thiếu yêu cầu xác nhận OCR.");
        if (string.IsNullOrWhiteSpace(request.Actor)) throw new BusinessRuleException("Người xác nhận OCR là bắt buộc.");

        var document = await GetDocumentAsync(documentId)
            ?? throw new BusinessRuleException($"Không tìm thấy tài liệu #{documentId}.");
        var fields = request.Fields?.Select(field => field with { Confirmed = true }).ToList() ?? [];
        if (fields.Count == 0)
        {
            fields = BuildOcrExtraction(document, "GEMINI", document.Description ?? "", CalculateOcrConfidence(document, "GEMINI"), confirmed: true).Fields.ToList();
        }
        if (fields.Count == 0)
        {
            throw new BusinessRuleException("Chưa có trường OCR để xác nhận.");
        }

        var metadata = string.Join(Environment.NewLine, fields.Select(item => $"{item.Label}: {item.Value}"));
        var previousStatus = string.IsNullOrWhiteSpace(document.OcrStatus) ? "PENDING" : document.OcrStatus;
        await CreateDocumentVersionAsync(documentId, new DocumentVersionRequest(request.Actor, "Lưu phiên bản trước khi xác nhận OCR"));
        await UpdateDocumentOcrAsync(documentId, "CONFIRMED", TrimText(metadata, 1000));
        await InsertWorkflowEventAsync("DOCUMENT", documentId, "CONFIRM_OCR", previousStatus, "CONFIRMED", request.Note, request.Actor, request.UnitCode);
        await InsertNotificationAsync("DOCUMENT", documentId, document.Code, request.Actor, $"Tài liệu {document.Code} đã xác nhận OCR", request.Note ?? "Dữ liệu OCR đã lưu chính thức vào Oracle.");

        var confidence = fields.Count == 0 ? 0 : Math.Round(fields.Average(item => item.Confidence), 2);
        return new Gd2OcrConfirmationResult(
            documentId,
            document.Code,
            DetectOcrDocumentType(document, metadata),
            confidence,
            "CONFIRMED",
            DateTime.Now,
            fields);
    }

    public async Task<IReadOnlyList<Gd2OcrResultDto>> ProcessOcrBatchAsync(Gd2OcrProcessRequest request)
    {
        var requestedIds = request.DocumentIds?.Where(id => id > 0).Distinct().ToList();
        var documents = await GetDocumentsAsync(null);
        var targetIds = requestedIds is { Count: > 0 }
            ? requestedIds
            : documents
                .Where(item => NormalizeStatus(item.OcrStatus) is "PENDING" or "ERROR")
                .Select(item => item.Id)
                .ToList();
        if (targetIds.Count == 0) throw new BusinessRuleException("Không có tài liệu nào cần OCR.");

        var results = new List<Gd2OcrResultDto>();
        foreach (var id in targetIds)
        {
            results.Add(await ProcessOcrAsync(id, request));
        }
        return results;
    }

    public async Task<Gd2DocumentSearchResult> SearchDocumentsAsync(Gd2DocumentSearchRequest request)
    {
        var page = Math.Max(1, request.Page);
        var pageSize = Math.Clamp(request.PageSize <= 0 ? 10 : request.PageSize, 5, 2000);
        var query = request.Query?.Trim();
        var metadata = request.Metadata?.Trim();
        var documentType = request.DocumentType?.Trim();
        var status = request.Status?.Trim();
        var ocrStatus = request.OcrStatus?.Trim();

        var conditions = new List<string> { "1=1" };
        var parameterValues = new List<(string Name, object? Value)>();
        void AddCondition(string sql, string name, object? value)
        {
            conditions.Add(sql);
            parameterValues.Add((name, value));
        }

        if (request.StorageId is > 0)
            AddCondition("""
                dos.STORAGE_ID IN (
                    SELECT storage_tree.ID
                    FROM DMS_STORAGE_LOCATIONS storage_tree
                    START WITH storage_tree.ID=:storageId
                    CONNECT BY NOCYCLE PRIOR storage_tree.ID=storage_tree.PARENT_ID
                )
                """, "storageId", request.StorageId.Value);
        if (request.DossierId is > 0)
            AddCondition("doc.DOSSIER_ID=:dossierId", "dossierId", request.DossierId.Value);
        if (!string.IsNullOrWhiteSpace(query))
            AddCondition("UPPER(NVL(doc.CODE, '') || ' ' || NVL(doc.TITLE, '') || ' ' || NVL(doc.FILE_NAME, '') || ' ' || NVL(doc.DESCRIPTION, '')) LIKE :query", "query", $"%{query.ToUpperInvariant()}%");
        if (!string.IsNullOrWhiteSpace(metadata))
            AddCondition("UPPER(NVL(doc.DESCRIPTION, '') || ' ' || NVL(doc.FILE_NAME, '')) LIKE :metadata", "metadata", $"%{metadata.ToUpperInvariant()}%");
        if (!string.IsNullOrWhiteSpace(documentType))
            AddCondition("UPPER(NVL(doc.DESCRIPTION, '') || ' ' || NVL(doc.FILE_NAME, '')) LIKE :documentType", "documentType", $"%{documentType.ToUpperInvariant()}%");
        if (!string.IsNullOrWhiteSpace(status))
            AddCondition("UPPER(NVL(doc.STATUS, 'DRAFT'))=:status", "status", NormalizeStatus(status));
        if (!string.IsNullOrWhiteSpace(ocrStatus))
            AddCondition("UPPER(NVL(doc.OCR_STATUS, 'PENDING'))=:ocrStatus", "ocrStatus", NormalizeStatus(ocrStatus));
        if (request.FromDate.HasValue)
            AddCondition("doc.CREATED_AT>=:fromDate", "fromDate", request.FromDate.Value.Date);
        if (request.ToDate.HasValue)
            AddCondition("doc.CREATED_AT<:toDate", "toDate", request.ToDate.Value.Date.AddDays(1));

        var fromAndWhere = $"""
            FROM DMS_DOCUMENTS doc
            INNER JOIN DMS_DOSSIERS dos ON dos.ID=doc.DOSSIER_ID
            WHERE {string.Join(" AND ", conditions)}
            """;
        OracleParameter[] Parameters() => parameterValues.Select(item => P(item.Name, item.Value)).ToArray();

        var total = Convert.ToInt32(await ExecuteScalarAsync($"SELECT COUNT(*) {fromAndWhere}", Parameters()) ?? 0);
        var itemParameters = Parameters().ToList();
        itemParameters.Add(P("offsetRows", (page - 1) * pageSize));
        itemParameters.Add(P("pageSize", pageSize));
        var items = await QueryAsync($"""
            SELECT doc.ID, doc.DOSSIER_ID, doc.CODE, doc.TITLE, doc.FILE_NAME, doc.OCR_STATUS, doc.STATUS, doc.DESCRIPTION
            {fromAndWhere}
            ORDER BY doc.ID DESC
            OFFSET :offsetRows ROWS FETCH NEXT :pageSize ROWS ONLY
            """, MapDocument, itemParameters.ToArray());

        return new Gd2DocumentSearchResult(items, page, pageSize, total, Math.Max(1, (int)Math.Ceiling(total / (double)pageSize)), DateTime.Now);
    }

    public async Task<IReadOnlyList<Gd2DocumentTreeNodeDto>> GetDocumentTreeAsync()
    {
        var storages = await GetStorageLocationsAsync();
        var dossiers = await GetDossiersAsync();
        var documents = await GetDocumentsAsync(null);
        Gd2DocumentTreeNodeDto DossierNode(DossierDto dossier)
        {
            var children = documents
                .Where(document => document.DossierId == dossier.Id)
                .GroupBy(document => DetectOcrDocumentType(document, document.Description))
                .OrderBy(group => group.Key)
                .Select(group => new Gd2DocumentTreeNodeDto(
                    $"type-{dossier.Id}-{group.Key}",
                    group.Key,
                    "DOCUMENT_TYPE",
                    null,
                    group.Count(),
                    []))
                .ToList();

            return new Gd2DocumentTreeNodeDto(
                $"dossier-{dossier.Id}",
                $"{dossier.Code} - {dossier.Title}",
                "DOSSIER",
                dossier.Id,
                children.Sum(child => child.Count),
                children);
        }

        var storageNodes = storages
            .OrderBy(storage => storage.Code)
            .Select(storage =>
            {
                var children = dossiers
                    .Where(dossier => dossier.StorageId == storage.Id)
                    .OrderBy(dossier => dossier.Code)
                    .Select(DossierNode)
                    .ToList();
                return new Gd2DocumentTreeNodeDto(
                    $"storage-{storage.Id}",
                    $"{storage.Code} - {storage.Name}",
                    "STORAGE",
                    storage.Id,
                    children.Sum(child => child.Count),
                    children);
            })
            .ToList();

        return [new("root", "Tất cả kho lưu trữ", "ROOT", null, documents.Count, storageNodes)];
    }

