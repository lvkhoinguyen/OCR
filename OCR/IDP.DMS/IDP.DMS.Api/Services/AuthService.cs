        await connection.OpenAsync();
        await using var command = BuildCommand(connection, """
            UPDATE DMS_USERS
            SET REFRESH_TOKEN_HASH=NULL, REFRESH_TOKEN_EXPIRES_AT=NULL, UPDATED_AT=SYSDATE
            WHERE ID=:id
            """, P("id", userId));
        await command.ExecuteNonQueryAsync();
    }

    private async Task<AuthTokenResponse> IssueTokensAsync(OracleConnection connection, AuthUserRecord user)
    {
        var now = DateTime.UtcNow;
        var accessExpiresAt = now.AddHours(Math.Clamp(_jwtOptions.AccessTokenHours, 1, 24));
        var refreshExpiresAt = now.AddDays(Math.Clamp(_jwtOptions.RefreshTokenDays, 1, 90));
        var refreshToken = Base64UrlEncoder.Encode(RandomNumberGenerator.GetBytes(64));
        var permissions = ParsePermissions(user.Permissions);

        var roleCode = user.RoleCode == "SYSTEM_ADMIN" ? "ADMIN" : user.RoleCode;
        var claims = new List<Claim>
        {
            new(JwtRegisteredClaimNames.Sub, user.Id.ToString()),
            new(ClaimTypes.NameIdentifier, user.Id.ToString()),
            new(ClaimTypes.Name, user.FullName),
            new(ClaimTypes.Role, roleCode),
            new(ClaimTypes.Role, user.RoleCode),
            new("role", roleCode),
            new("role", user.RoleCode),
            new(JwtRegisteredClaimNames.UniqueName, user.Username),
            new(JwtRegisteredClaimNames.Jti, Guid.NewGuid().ToString("N"))
        };
        claims.AddRange(permissions.Select(permission => new Claim(DmsPermissions.ClaimType, permission)));

        var credentials = new SigningCredentials(
            new SymmetricSecurityKey(Encoding.UTF8.GetBytes(_jwtOptions.SigningKey)),
            SecurityAlgorithms.HmacSha256);
        var token = new JwtSecurityToken(
            issuer: _jwtOptions.Issuer,
            audience: _jwtOptions.Audience,
            claims: claims,
            notBefore: now,
            expires: accessExpiresAt,
            signingCredentials: credentials);
        var accessToken = new JwtSecurityTokenHandler().WriteToken(token);

        await using var command = BuildCommand(connection, """
            UPDATE DMS_USERS
            SET REFRESH_TOKEN_HASH=:refreshHash, REFRESH_TOKEN_EXPIRES_AT=:refreshExpiresAt,
                LAST_LOGIN_AT=SYSDATE, UPDATED_AT=SYSDATE
            WHERE ID=:id
            """,
            P("refreshHash", HashRefreshToken(refreshToken)),
            P("refreshExpiresAt", refreshExpiresAt),
            P("id", user.Id));
        await command.ExecuteNonQueryAsync();

        return new AuthTokenResponse(accessToken, refreshToken, accessExpiresAt, refreshExpiresAt, ToDto(user));
    }

    private static async Task<AuthUserRecord?> FindUserByUsernameAsync(OracleConnection connection, string username) =>
        await QueryUserAsync(connection, """
            SELECT u.ID, u.USERNAME, u.PASSWORD_HASH, NVL(u.FULL_NAME, u.NAME), u.EMAIL, u.STATUS,
                   r.ID, r.CODE, r.NAME, r.PERMISSIONS, u.REFRESH_TOKEN_HASH, u.REFRESH_TOKEN_EXPIRES_AT
            FROM DMS_USERS u
            JOIN DMS_ROLES r ON r.ID = u.ROLE_ID AND r.STATUS = 'ACTIVE'
            WHERE u.USERNAME=:username
            """, P("username", username));

    private static async Task<AuthUserRecord?> FindUserByIdAsync(OracleConnection connection, long id) =>
        await QueryUserAsync(connection, """
            SELECT u.ID, u.USERNAME, u.PASSWORD_HASH, NVL(u.FULL_NAME, u.NAME), u.EMAIL, u.STATUS,
                   r.ID, r.CODE, r.NAME, r.PERMISSIONS, u.REFRESH_TOKEN_HASH, u.REFRESH_TOKEN_EXPIRES_AT
            FROM DMS_USERS u
            JOIN DMS_ROLES r ON r.ID = u.ROLE_ID AND r.STATUS = 'ACTIVE'
            WHERE u.ID=:id AND u.USERNAME IS NOT NULL AND u.PASSWORD_HASH IS NOT NULL
            """, P("id", id));

    private static async Task<AuthUserRecord?> FindUserByRefreshTokenAsync(OracleConnection connection, string refreshHash) =>
        await QueryUserAsync(connection, """
            SELECT u.ID, u.USERNAME, u.PASSWORD_HASH, NVL(u.FULL_NAME, u.NAME), u.EMAIL, u.STATUS,
                   r.ID, r.CODE, r.NAME, r.PERMISSIONS, u.REFRESH_TOKEN_HASH, u.REFRESH_TOKEN_EXPIRES_AT
            FROM DMS_USERS u
            JOIN DMS_ROLES r ON r.ID = u.ROLE_ID AND r.STATUS = 'ACTIVE'
            WHERE u.REFRESH_TOKEN_HASH=:refreshHash
            """, P("refreshHash", refreshHash));

    private static async Task<AuthUserRecord?> QueryUserAsync(
        OracleConnection connection,
        string sql,
        params OracleParameter[] parameters)
    {
        await using var command = BuildCommand(connection, sql, parameters);
        await using var reader = await command.ExecuteReaderAsync();
        if (!await reader.ReadAsync())
        {
            return null;
        }

        return new AuthUserRecord(
            Convert.ToInt64(reader.GetValue(0)),
            reader.GetString(1),
            reader.GetString(2),
            reader.GetString(3),
            reader.IsDBNull(4) ? null : reader.GetString(4),
            reader.GetString(5),
            Convert.ToInt64(reader.GetValue(6)),
            reader.GetString(7),
            reader.GetString(8),
            reader.GetString(9),
            reader.IsDBNull(10) ? null : reader.GetString(10),
            reader.IsDBNull(11) ? null : reader.GetDateTime(11));
    }

    private static async Task<(long Id, string Code, string Name, string Permissions)?> FindRoleAsync(
        OracleConnection connection,
        string roleCode)
    {
        await using var command = BuildCommand(connection,
            "SELECT ID, CODE, NAME, PERMISSIONS FROM DMS_ROLES WHERE CODE=:code AND STATUS='ACTIVE'",
            P("code", roleCode));
        await using var reader = await command.ExecuteReaderAsync();
        if (!await reader.ReadAsync())
        {
            return null;
        }

        return (Convert.ToInt64(reader.GetValue(0)), reader.GetString(1), reader.GetString(2), reader.GetString(3));
    }

    private static AuthUserDto ToDto(AuthUserRecord user) =>
        new(user.Id, user.Username, user.FullName, user.Email,
            user.RoleCode == "SYSTEM_ADMIN" ? "ADMIN" : user.RoleCode,
            user.RoleName, ParsePermissions(user.Permissions));

    private static IReadOnlyList<string> ParsePermissions(string permissions) =>
        permissions.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(value => value.ToUpperInvariant())
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToArray();

    private static string NormalizeUsername(string username) => username.Trim().ToLowerInvariant();

    private static void ValidateUsername(string username)
    {
        if (!Regex.IsMatch(username, "^[a-z0-9._-]{3,80}$", RegexOptions.CultureInvariant))
        {
            throw new BusinessRuleException("Tên đăng nhập chỉ gồm chữ không dấu, số, dấu chấm, gạch dưới hoặc gạch ngang.");
        }
    }

    private static void ValidatePassword(string password)
    {
        if (password.Length < 8 || !password.Any(char.IsLetter) || !password.Any(char.IsDigit))
        {
            throw new BusinessRuleException("Mật khẩu phải có ít nhất 8 ký tự, gồm cả chữ và số.");
        }
    }

    private static string HashRefreshToken(string token) =>
        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(token)));

    private OracleConnection CreateConnection() => new(_connectionString);

    private static OracleParameter P(string name, object? value) => new(name, value ?? DBNull.Value);

    private static OracleCommand BuildCommand(
        OracleConnection connection,
        string sql,
        params OracleParameter[] parameters)
    {
        var command = connection.CreateCommand();
        command.BindByName = true;
        command.CommandText = sql;
        command.Parameters.AddRange(parameters);
        return command;
    }

    private static async Task<object?> ExecuteScalarAsync(OracleConnection connection, string sql)
    {
        await using var command = BuildCommand(connection, sql);
        return await command.ExecuteScalarAsync();
    }

    private static async Task ExecuteDdlAsync(OracleConnection connection, string sql)
    {
        await using var command = BuildCommand(connection, sql);
        try
        {
            await command.ExecuteNonQueryAsync();
        }
        catch (OracleException exception) when (exception.Number is 955 or 1408 or 1430 or 2275)
        {
            // Bảng/index/cột đã tồn tại.
        }
    }

    private static Task AddColumnIfMissingAsync(OracleConnection connection, string table, string columnDefinition) =>
        ExecuteDdlAsync(connection, $"ALTER TABLE {table} ADD ({columnDefinition})");

    private static async Task SeedRoleAsync(
        OracleConnection connection,
        string code,
        string name,
        string permissions)
    {
        await using var command = BuildCommand(connection, """
            MERGE INTO DMS_ROLES target
            USING (SELECT :code CODE, :name NAME, :permissions PERMISSIONS FROM DUAL) source
            ON (target.CODE = source.CODE)
            WHEN MATCHED THEN UPDATE SET
                target.NAME=source.NAME, target.PERMISSIONS=source.PERMISSIONS,
                target.STATUS='ACTIVE', target.UPDATED_AT=SYSDATE
            WHEN NOT MATCHED THEN INSERT
                (CODE, NAME, PERMISSIONS, STATUS, CREATED_AT)
            VALUES
                (source.CODE, source.NAME, source.PERMISSIONS, 'ACTIVE', SYSDATE)
            """, P("code", code), P("name", name), P("permissions", permissions));
        await command.ExecuteNonQueryAsync();
    }

    private static async Task SeedDefaultUsersAsync(OracleConnection connection)
    {
        var adminRole = await FindRoleAsync(connection, "ADMIN")
            ?? await FindRoleAsync(connection, "SYSTEM_ADMIN");

        var usersToSeed = new[]
        {
            (Username: "admin", Password: "Admin@123", RoleCode: "ADMIN", FullName: "Quản trị viên hệ thống", Email: "admin@idp.vn"),
            (Username: "nhaplieu", Password: "User@123", RoleCode: "DATA_ENTRY", FullName: "Cán bộ nhập liệu", Email: "nhaplieu@idp.vn"),
            (Username: "lanhdao", Password: "Approver@123", RoleCode: "APPROVER", FullName: "Cán bộ kiểm duyệt", Email: "lanhdao@idp.vn"),
            (Username: "khach", Password: "Guest@123", RoleCode: "PUBLIC", FullName: "Người dùng khai thác", Email: "khach@idp.vn")
        };

        foreach (var u in usersToSeed)
        {
            var targetRole = await FindRoleAsync(connection, u.RoleCode) ?? adminRole;
            if (!targetRole.HasValue) continue;

            var existing = Convert.ToInt64(await ExecuteScalarAsync(connection,
                $"SELECT COUNT(*) FROM DMS_USERS WHERE LOWER(USERNAME)='{u.Username.ToLowerInvariant()}'"));

            var passwordHash = BCrypt.Net.BCrypt.HashPassword(u.Password, workFactor: 11);

            if (existing == 0)
            {
                var sql = """
                    INSERT INTO DMS_USERS
                        (CODE, NAME, STATUS, USERNAME, PASSWORD_HASH, FULL_NAME, EMAIL, ROLE_ID, CREATED_AT)
                    VALUES
                        (:code, :name, 'ACTIVE', :username, :passwordHash, :fullName, :email, :roleId, SYSDATE)
                    """;
                await using var command = BuildCommand(connection, sql,
                    P("code", u.Username),
                    P("name", u.FullName),
                    P("username", u.Username),
                    P("passwordHash", passwordHash),
                    P("fullName", u.FullName),
                    P("email", u.Email),
                    P("roleId", targetRole.Value.Id));
                await command.ExecuteNonQueryAsync();
            }
            else if (u.Username == "admin")
            {
                await using var updateCmd = BuildCommand(connection,
                    "UPDATE DMS_USERS SET PASSWORD_HASH=:passwordHash, ROLE_ID=:roleId WHERE LOWER(USERNAME)='admin'",
                    P("passwordHash", passwordHash),
                    P("roleId", targetRole.Value.Id));
                await updateCmd.ExecuteNonQueryAsync();
            }
        }
    }

    private AuthTokenResponse IssueOfflineToken((string Username, string Password, string RoleCode, string RoleName, string FullName, string Permissions) user)
    {
        var now = DateTime.UtcNow;
        var accessExpiresAt = now.AddHours(Math.Clamp(_jwtOptions.AccessTokenHours, 1, 24));
        var refreshExpiresAt = now.AddDays(Math.Clamp(_jwtOptions.RefreshTokenDays, 1, 90));
        var refreshToken = Base64UrlEncoder.Encode(RandomNumberGenerator.GetBytes(64));
        var permissions = ParsePermissions(user.Permissions);

        var claims = new List<Claim>
        {
            new(JwtRegisteredClaimNames.Sub, "1"),
            new(ClaimTypes.NameIdentifier, "1"),
            new(ClaimTypes.Name, user.FullName),
            new(ClaimTypes.Role, user.RoleCode),
            new(ClaimTypes.Role, user.RoleCode == "SYSTEM_ADMIN" ? "ADMIN" : user.RoleCode),
            new("role", user.RoleCode),
            new("role", user.RoleCode == "SYSTEM_ADMIN" ? "ADMIN" : user.RoleCode),
            new(JwtRegisteredClaimNames.UniqueName, user.Username),
            new(JwtRegisteredClaimNames.Jti, Guid.NewGuid().ToString("N"))
        };
        claims.AddRange(permissions.Select(permission => new Claim(DmsPermissions.ClaimType, permission)));

        var credentials = new SigningCredentials(
            new SymmetricSecurityKey(Encoding.UTF8.GetBytes(_jwtOptions.SigningKey)),
            SecurityAlgorithms.HmacSha256);
        var token = new JwtSecurityToken(
            issuer: _jwtOptions.Issuer,
            audience: _jwtOptions.Audience,
            claims: claims,
            notBefore: now,
            expires: accessExpiresAt,
            signingCredentials: credentials);
        var accessToken = new JwtSecurityTokenHandler().WriteToken(token);

        var dto = new AuthUserDto(1, user.Username, user.FullName, $"{user.Username}@idp.vn", user.RoleCode, user.RoleName, permissions);
        return new AuthTokenResponse(accessToken, refreshToken, accessExpiresAt, refreshExpiresAt, dto);
    }
