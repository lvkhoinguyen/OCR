    public async Task<long> CreateStorageLocationAsync(StorageLocationRequest request)
    {
        const string sql = """
            INSERT INTO DMS_STORAGE_LOCATIONS (CODE, NAME, LOCATION_TYPE, PARENT_ID, STATUS, CAPACITY)
            VALUES (:code, :name, :locationType, :parentId, :status, :capacity)
            RETURNING ID INTO :id
            """;
        return await InsertReturningIdAsync(sql, StorageParameters(request));
    }

