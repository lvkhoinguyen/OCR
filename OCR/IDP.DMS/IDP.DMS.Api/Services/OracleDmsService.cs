    private static string NormalizeExportFormat(string? format)
    {
        var normalized = string.IsNullOrWhiteSpace(format) ? "EXCEL" : format.Trim().ToUpperInvariant();
        return normalized is "PDF" or "EXCEL" or "XLS" or "XLSX"
            ? normalized
            : throw new BusinessRuleException("Định dạng xuất chỉ hỗ trợ PDF hoặc Excel.");
    }

