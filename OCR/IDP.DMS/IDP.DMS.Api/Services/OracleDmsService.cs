    public async Task RefreshBatchImportJobAsync(long jobId)
    {
        var counters = await QuerySingleAsync("""
            SELECT
                COUNT(*),
                SUM(CASE WHEN STATUS NOT IN ('VALIDATION_ERROR', 'IMPORT_ERROR') THEN 1 ELSE 0 END),
                COUNT(DISTINCT DOSSIER_ID),
                SUM(CASE WHEN DOCUMENT_ID IS NOT NULL THEN 1 ELSE 0 END),
                SUM(CASE WHEN STATUS IN ('VALIDATION_ERROR', 'IMPORT_ERROR') THEN 1 ELSE 0 END),
                SUM(CASE WHEN DOCUMENT_ID IS NOT NULL THEN 1 ELSE 0 END),
                SUM(CASE WHEN STATUS='OCR_DONE' THEN 1 ELSE 0 END),
                SUM(CASE WHEN STATUS='OCR_ERROR' THEN 1 ELSE 0 END),
                SUM(CASE WHEN STATUS IN ('OCR_QUEUED', 'OCR_PROCESSING') THEN 1 ELSE 0 END)
            FROM DMS_BATCH_IMPORT_ITEMS
            WHERE JOB_ID=:jobId
            """,
            reader => Enumerable.Range(0, 9).Select(index => Convert.ToInt32(reader.IsDBNull(index) ? 0 : reader.GetDecimal(index))).ToArray(),
            P("jobId", jobId)) ?? new int[9];

        var pending = counters[8];
        var status = pending > 0
            ? "OCR_PROCESSING"
            : counters[4] > 0 || counters[7] > 0 ? "COMPLETED_WITH_ERRORS" : "COMPLETED";
        await ExecuteAsync("""
            UPDATE DMS_BATCH_IMPORT_JOBS
            SET STATUS=:status, TOTAL_ROWS=:totalRows, VALID_ROWS=:validRows,
                IMPORTED_DOSSIERS=:importedDossiers, IMPORTED_DOCUMENTS=:importedDocuments,
                FAILED_ROWS=:failedRows, OCR_QUEUED=:ocrQueued, OCR_COMPLETED=:ocrCompleted,
                OCR_FAILED=:ocrFailed,
                COMPLETED_AT=CASE WHEN :pending=0 THEN SYSDATE ELSE NULL END
            WHERE ID=:id
            """,
            P("status", status), P("totalRows", counters[0]), P("validRows", counters[1]),
            P("importedDossiers", counters[2]), P("importedDocuments", counters[3]),
            P("failedRows", counters[4]), P("ocrQueued", counters[5]),
            P("ocrCompleted", counters[6]), P("ocrFailed", counters[7]),
            P("pending", pending), P("id", jobId));
    }

