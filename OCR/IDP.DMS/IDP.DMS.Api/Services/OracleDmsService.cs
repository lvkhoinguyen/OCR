    private async Task<long> InsertReturningIdAsync(string sql, IReadOnlyList<OracleParameter> parameters)
    {
        await using var connection = CreateConnection();
        await connection.OpenAsync();
        await using var command = BuildCommand(connection, sql, parameters.ToArray());
        var idParameter = new OracleParameter("id", OracleDbType.Int64, ParameterDirection.Output);
        command.Parameters.Add(idParameter);
        await command.ExecuteNonQueryAsync();
        return Convert.ToInt64(idParameter.Value.ToString());
    }

    private static OracleCommand BuildCommand(OracleConnection connection, string sql, params OracleParameter[] parameters)
    {
        var command = connection.CreateCommand();
        command.BindByName = true;
        command.CommandText = sql;
        command.Parameters.AddRange(parameters);
        return command;
    }

