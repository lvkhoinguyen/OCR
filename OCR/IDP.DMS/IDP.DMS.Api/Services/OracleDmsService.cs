    private async Task ValidateDossierAsync(DossierRequest request, long? currentId = null)
    {
        ValidateDossier(request);
        var duplicateCount = Convert.ToInt64(await ExecuteScalarAsync("""
            SELECT COUNT(*)
            FROM DMS_DOSSIERS
