    private readonly string _connectionString;
    private readonly ILogger<OracleDmsService> _logger;

    public OracleDmsService(IConfiguration configuration, IWebHostEnvironment environment, ILogger<OracleDmsService> logger)
    {
        _logger = logger;
        var configConnStr = configuration.GetConnectionString("OracleDms");
        if (!string.IsNullOrWhiteSpace(configConnStr) && !configConnStr.Contains("YOUR_ORACLE_USER"))
        {
            _connectionString = configConnStr;
        }
        else
        {
            var root = Directory.GetParent(environment.ContentRootPath)?.FullName ?? environment.ContentRootPath;
            var descriptorPath = Path.Combine(root, "cnn_ora.txt");
            if (File.Exists(descriptorPath))
            {
                var descriptor = File.ReadAllText(descriptorPath).Trim();
                _connectionString = $"User Id=dummyerp;Password=dummyerp;Data Source={descriptor};";
                _logger.LogWarning(
                    "Using fallback Oracle connection from cnn_ora.txt. Set ConnectionStrings:OracleDms in appsettings for production.");
            }
            else
            {
                _connectionString = "User Id=dummyerp;Password=dummyerp;Data Source=localhost:1521/XEPDB1;";
                _logger.LogWarning(
                    "Using hardcoded fallback Oracle connection string. This is intended for local development only. " +
                    "Set ConnectionStrings:OracleDms in appsettings.json for any deployed environment.");
            }
        }
    }

