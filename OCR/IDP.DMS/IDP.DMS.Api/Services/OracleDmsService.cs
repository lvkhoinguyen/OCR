    private static IReadOnlyList<WorkflowRuntimeStepDto> BuildRuntimeWorkflowSteps(string currentStatus)
    {
        string[] statuses = ["DRAFT", "PENDING", "APPROVED", "PUBLISHED", "CONFIRMED"];
        var currentIndex = Array.IndexOf(statuses, currentStatus);
        if (currentStatus is "NEEDS_SUPPLEMENT" or "REJECTED") currentIndex = 1;

        return statuses.Select((status, index) => new WorkflowRuntimeStepDto(
            status,
            status switch
            {
                "DRAFT" => "Khởi tạo hồ sơ",
                "PENDING" => "Chờ kiểm duyệt",
                "APPROVED" => "Đã phê duyệt",
                "PUBLISHED" => "Đã xuất bản/ký số",
                "CONFIRMED" => "Xác nhận hoàn tất",
                _ => status
            },
            status is "DRAFT" ? "CHUYEN_VIEN" : status is "PENDING" ? "KIEM_DUYET" : "LANH_DAO",
            "current-user",
            DateTime.Now.AddDays(index + 1),
            index < currentIndex ? "DONE" : index == currentIndex ? "CURRENT" : "WAITING")).ToList();
    }

