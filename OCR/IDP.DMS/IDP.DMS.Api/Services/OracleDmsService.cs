    private async Task ValidateBorrowRequestAsync(BorrowRequestRequest request, long? currentId = null)
    {
        if (string.IsNullOrWhiteSpace(request.Borrower))
        {
            throw new BusinessRuleException("Người mượn là bắt buộc.");
        }
        if (request.BorrowFrom.HasValue && request.BorrowTo.HasValue && request.BorrowFrom > request.BorrowTo)
        {
            throw new BusinessRuleException("Ngày mượn không được lớn hơn ngày trả.");
        }
        if (await GetDossierAsync(request.DossierId) is null)
        {
            throw new BusinessRuleException($"Hồ sơ #{request.DossierId} không tồn tại.");
        }

        var duplicateCount = Convert.ToInt64(await ExecuteScalarAsync("""
            SELECT COUNT(*)
            FROM DMS_BORROW_REQUESTS
            WHERE DOSSIER_ID=:dossierId
              AND UPPER(BORROWER)=UPPER(:borrower)
              AND UPPER(NVL(STATUS, 'PENDING')) IN ('PENDING', 'APPROVED', 'BORROWED')
              AND (:currentId IS NULL OR ID<>:currentId)
            """,
            P("dossierId", request.DossierId),
            P("borrower", request.Borrower),
            P("currentId", currentId)) ?? 0);
        if (duplicateCount > 0)
        {
            throw new BusinessRuleException("Người dùng đã có yêu cầu mượn đang xử lý cho hồ sơ này.");
        }
    }

