            SET CODE=:code, NAME=:name, LOCATION_TYPE=:locationType, PARENT_ID=:parentId, STATUS=:status, CAPACITY=:capacity, UPDATED_AT=SYSDATE
            WHERE ID=:id
            """, [.. StorageParameters(request), P("id", id)]);

