    public async Task<PdfSignatureCommitResult> CommitPdfSignatureAsync(PdfSignatureCommitRequest request)
    {
        await using var connection = CreateConnection();
        await connection.OpenAsync();
        await using var transaction = (OracleTransaction)await connection.BeginTransactionAsync();

        async Task<int> ExecuteInTransactionAsync(string sql, params OracleParameter[] parameters)
        {
            await using var command = BuildCommand(connection, sql, parameters);
            command.Transaction = transaction;
            return await command.ExecuteNonQueryAsync();
        }

        async Task<long> InsertAndReturnIdAsync(string sql, params OracleParameter[] parameters)
        {
            await using var command = BuildCommand(connection, sql, parameters);
            command.Transaction = transaction;
            var idParameter = new OracleParameter("id", OracleDbType.Int64, ParameterDirection.Output);
            command.Parameters.Add(idParameter);
            await command.ExecuteNonQueryAsync();
            return Convert.ToInt64(idParameter.Value.ToString());
        }

        try
        {
            string code;
            string title;
            string? ocrStatus;
            string? description;
            string currentStatus;
            await using (var documentCommand = BuildCommand(connection, """
                SELECT CODE, TITLE, OCR_STATUS, STATUS, DESCRIPTION
                FROM DMS_DOCUMENTS
                WHERE ID=:id
                FOR UPDATE
                """, P("id", request.DocumentId)))
            {
                documentCommand.Transaction = transaction;
                await using var reader = await documentCommand.ExecuteReaderAsync();
                if (!await reader.ReadAsync())
                    throw new BusinessRuleException($"Không tìm thấy tài liệu #{request.DocumentId}.");
                code = reader.GetString(0);
                title = reader.GetString(1);
                ocrStatus = NString(reader, 2);
                currentStatus = (NString(reader, 3) ?? "DRAFT").Trim().ToUpperInvariant();
                description = NString(reader, 4);
            }

            if (currentStatus != "APPROVED")
                throw new BusinessRuleException("Trạng thái tài liệu đã thay đổi; chỉ tài liệu APPROVED mới được ký số.");

            await using (var duplicateCommand = BuildCommand(connection,
                "SELECT COUNT(*) FROM DMS_DIGITAL_SIGNATURES WHERE DOCUMENT_ID=:documentId",
                P("documentId", request.DocumentId)))
            {
                duplicateCommand.Transaction = transaction;
                if (Convert.ToInt64(await duplicateCommand.ExecuteScalarAsync()) > 0)
                    throw new BusinessRuleException("Tài liệu đã có chữ ký số. Không ký đè vì có thể làm mất hiệu lực chữ ký hiện hữu.");
            }

            int versionNumber;
            await using (var versionCommand = BuildCommand(connection,
                "SELECT NVL(MAX(VERSION_NO), 0) + 1 FROM DMS_DOCUMENT_VERSIONS WHERE DOCUMENT_ID=:documentId",
                P("documentId", request.DocumentId)))
            {
                versionCommand.Transaction = transaction;
                versionNumber = Convert.ToInt32(await versionCommand.ExecuteScalarAsync());
            }

            var versionId = await InsertAndReturnIdAsync("""
                INSERT INTO DMS_DOCUMENT_VERSIONS
                    (DOCUMENT_ID, VERSION_NO, CODE, TITLE, FILE_NAME, OCR_STATUS, STATUS,
                     DESCRIPTION, NOTE, CREATED_BY)
                VALUES
                    (:documentId, :versionNo, :code, :title, :fileName, :ocrStatus, 'PUBLISHED',
                     :description, :note, :createdBy)
                RETURNING ID INTO :id
                """,
                P("documentId", request.DocumentId),
                P("versionNo", versionNumber),
                P("code", code),
                P("title", title),
                P("fileName", request.SignedFileName),
                P("ocrStatus", ocrStatus),
                P("description", description),
                P("note", $"PDF đã ký số bởi {request.Signer} lúc {request.SignedAt.ToLocalTime():dd/MM/yyyy HH:mm:ss}"),
                P("createdBy", request.Signer));

            await ExecuteInTransactionAsync("""
                UPDATE DMS_DOCUMENTS
                SET FILE_NAME=:fileName, STATUS='PUBLISHED', UPDATED_AT=SYSDATE
                WHERE ID=:id
                """, P("fileName", request.SignedFileName), P("id", request.DocumentId));

            var validationStatus = request.CertificateTrusted
                ? "CHAIN_TRUSTED_NO_REVOCATION"
                : "SIGNED_UNTRUSTED_CERTIFICATE";
            var appearance = $"Ký bởi: {request.Signer}; Ngày ký: {request.SignedAt.ToLocalTime():dd/MM/yyyy HH:mm:ss}; Chứng thư: {request.CertificateSubject}";
            var signatureId = await InsertAndReturnIdAsync("""
                INSERT INTO DMS_DIGITAL_SIGNATURES
                    (DOCUMENT_ID, SIGNER, PROVIDER, CERTIFICATE_TYPE, CERTIFICATE_SUBJECT,
                     CERTIFICATE_SERIAL, VALID_FROM, VALID_TO, SIGNED_AT, TIMESTAMP_AT,
                     OCSP_STATUS, CRL_STATUS, VALIDATION_STATUS, CERTIFICATE_TRUSTED,
                     PAGE_NUMBER, POS_X, POS_Y, WIDTH, HEIGHT, APPEARANCE_TEXT,
                     SOURCE_FILE_NAME, SIGNED_FILE_NAME, DOCUMENT_VERSION_ID, FILE_HASH_SHA256,
                     REASON, LOCATION_TEXT)
                VALUES
                    (:documentId, :signer, :provider, :certificateType, :certificateSubject,
                     :certificateSerial, :validFrom, :validTo, :signedAt, :timestampAt,
                     'NOT_CHECKED', 'NOT_CHECKED', :validationStatus, :certificateTrusted,
                     :pageNumber, :posX, :posY, :width, :height, :appearanceText,
                     :sourceFileName, :signedFileName, :documentVersionId, :fileHash,
                     :reason, :locationText)
                RETURNING ID INTO :id
                """,
                P("documentId", request.DocumentId),
                P("signer", request.Signer),
                P("provider", request.CertificateType),
                P("certificateType", request.CertificateType),
                P("certificateSubject", request.CertificateSubject),
                P("certificateSerial", request.CertificateSerial),
                P("validFrom", request.ValidFrom),
                P("validTo", request.ValidTo),
                P("signedAt", request.SignedAt),
                P("timestampAt", request.TimestampAt),
                P("validationStatus", validationStatus),
                P("certificateTrusted", request.CertificateTrusted ? 1 : 0),
                P("pageNumber", request.PageNumber),
                P("posX", request.PositionX),
                P("posY", request.PositionY),
                P("width", request.Width),
                P("height", request.Height),
                P("appearanceText", TrimText(appearance, 500)),
                P("sourceFileName", request.SourceFileName),
                P("signedFileName", request.SignedFileName),
                P("documentVersionId", versionId),
                P("fileHash", request.FileHashSha256),
                P("reason", request.Reason),
                P("locationText", request.Location));

            await ExecuteInTransactionAsync("""
                INSERT INTO DMS_WORKFLOW_EVENTS
                    (ENTITY_TYPE, ENTITY_ID, ACTION, FROM_STATUS, TO_STATUS, COMMENT_TEXT, ACTOR, UNIT_CODE)
                VALUES
                    ('DOCUMENT', :entityId, 'SIGN', 'APPROVED', 'PUBLISHED', :commentText, :actor, 'DEFAULT')
                """,
                P("entityId", request.DocumentId),
                P("commentText", $"Đã ký số PDF bằng {request.CertificateType}; SHA-256: {request.FileHashSha256}"),
                P("actor", request.Signer));

            await transaction.CommitAsync();
            return new PdfSignatureCommitResult(signatureId, versionId, versionNumber);
        }
        catch
        {
            await transaction.RollbackAsync();
            throw;
        }
    }

