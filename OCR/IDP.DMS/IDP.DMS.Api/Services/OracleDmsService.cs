    public async Task<WorkflowTransitionResult> TransitionWorkflowAsync(WorkflowTransitionRequest request)
    {
        var actor = string.IsNullOrWhiteSpace(request.Actor) ? "system" : request.Actor.Trim();
        request = request with { Actor = actor };

        var entityType = NormalizeEntityType(request.EntityType);
        var action = request.Action.Trim().ToUpperInvariant();
        var tableName = entityType switch
        {
            "DOSSIER" => "DMS_DOSSIERS",
            "DOCUMENT" => "DMS_DOCUMENTS",
            _ => "DMS_BORROW_REQUESTS"
        };

        if (entityType == "DOCUMENT")
        {
            await CreateDocumentVersionAsync(request.EntityId, new DocumentVersionRequest(
                request.Actor,
                $"Phiên bản trước thao tác workflow {action}: {request.Comment}"));
        }

        await using var connection = CreateConnection();
        await connection.OpenAsync();
        await using var transaction = (OracleTransaction)await connection.BeginTransactionAsync();

        try
        {
            string currentStatus;
            await using (var statusCommand = BuildCommand(connection,
                $"SELECT STATUS FROM {tableName} WHERE ID=:id FOR UPDATE", P("id", request.EntityId)))
            {
                statusCommand.Transaction = transaction;
                var statusValue = await statusCommand.ExecuteScalarAsync();
                if (statusValue is null || statusValue == DBNull.Value)
                {
                    throw new BusinessRuleException($"Không tìm thấy {EntityLabel(entityType)} #{request.EntityId}.");
                }
                currentStatus = Convert.ToString(statusValue)?.ToUpperInvariant() ?? "DRAFT";
            }

            var nextStatus = ResolveNextStatus(entityType, currentStatus, action);
            if (entityType == "DOSSIER" && !string.IsNullOrWhiteSpace(request.Comment) && action is "REQUEST_SUPPLEMENT" or "REJECT")
            {
                var prefix = action == "REQUEST_SUPPLEMENT" ? "[Yêu cầu bổ sung]: " : "[Từ chối]: ";
                await using var updateCommand = BuildCommand(connection,
                    $"UPDATE {tableName} SET STATUS=:status, DESCRIPTION=:description, UPDATED_AT=SYSDATE WHERE ID=:id",
                    P("status", nextStatus),
                    P("description", TrimText($"{prefix}{request.Comment.Trim()}", 950)),
                    P("id", request.EntityId));
                updateCommand.Transaction = transaction;
                await updateCommand.ExecuteNonQueryAsync();
            }
            else
            {
                await using var updateCommand = BuildCommand(connection,
                    $"UPDATE {tableName} SET STATUS=:status, UPDATED_AT=SYSDATE WHERE ID=:id",
                    P("status", nextStatus), P("id", request.EntityId));
                updateCommand.Transaction = transaction;
                await updateCommand.ExecuteNonQueryAsync();
            }

            await using (var eventCommand = BuildCommand(connection, """
                INSERT INTO DMS_WORKFLOW_EVENTS
                    (ENTITY_TYPE, ENTITY_ID, ACTION, FROM_STATUS, TO_STATUS, COMMENT_TEXT, ACTOR, UNIT_CODE)
                VALUES
                    (:entityType, :entityId, :action, :fromStatus, :toStatus, :commentText, :actor, :unitCode)
                """,
                P("entityType", entityType),
                P("entityId", request.EntityId),
                P("action", action),
                P("fromStatus", currentStatus),
                P("toStatus", nextStatus),
                P("commentText", request.Comment),
                P("actor", request.Actor),
                P("unitCode", request.UnitCode)))
            {
                eventCommand.Transaction = transaction;
                await eventCommand.ExecuteNonQueryAsync();
            }

            var recipient = string.IsNullOrWhiteSpace(request.Recipient) ? request.Actor : request.Recipient;
            var notificationCode = $"TB-{DateTime.UtcNow:yyyyMMddHHmmssfff}-{request.EntityId}";
            await using (var notificationCommand = BuildCommand(connection, """
                INSERT INTO DMS_NOTIFICATIONS
                    (CODE, ENTITY_TYPE, ENTITY_ID, RECIPIENT, CHANNEL, TITLE, CONTENT_TEXT, STATUS, SENT_AT)
                VALUES
                    (:code, :entityType, :entityId, :recipient, 'SYSTEM', :title, :contentText, 'SENT', SYSDATE)
                """,
                P("code", notificationCode),
                P("entityType", entityType),
                P("entityId", request.EntityId),
                P("recipient", recipient),
                P("title", $"{EntityLabel(entityType)} #{request.EntityId} chuyển sang {nextStatus}"),
                P("contentText", request.Comment)))
            {
                notificationCommand.Transaction = transaction;
                await notificationCommand.ExecuteNonQueryAsync();
            }

            await transaction.CommitAsync();
            return new WorkflowTransitionResult(
                entityType,
                request.EntityId,
                currentStatus,
                nextStatus,
                action,
                DateTime.Now);
        }
        catch
        {
            await transaction.RollbackAsync();
            throw;
        }
    }

    public async Task<OcrWorkflowSubmissionResult> SubmitOcrForReviewAsync(
        long documentId,
        string actor,
        string? unitCode,
        string? recipient = null)
    {
        actor = string.IsNullOrWhiteSpace(actor) ? "system" : actor.Trim();
        unitCode = string.IsNullOrWhiteSpace(unitCode) ? "DEFAULT" : unitCode.Trim().ToUpperInvariant();
        recipient = string.IsNullOrWhiteSpace(recipient) ? "LANH_DAO_DON_VI" : recipient.Trim();

        await using var connection = CreateConnection();
        await connection.OpenAsync();
        await using var transaction = (OracleTransaction)await connection.BeginTransactionAsync();

        async Task<int> ExecuteInTransactionAsync(string sql, params OracleParameter[] parameters)
        {
            await using var command = BuildCommand(connection, sql, parameters);
            command.Transaction = transaction;
            return await command.ExecuteNonQueryAsync();
        }

        try
        {
            long dossierId;
            string previousDocumentStatus;
            string ocrStatus;
            await using (var documentCommand = BuildCommand(connection, """
                SELECT DOSSIER_ID, NVL(STATUS, 'DRAFT'), NVL(OCR_STATUS, 'PENDING')
                FROM DMS_DOCUMENTS
                WHERE ID=:id
                FOR UPDATE
                """, P("id", documentId)))
            {
                documentCommand.Transaction = transaction;
                await using var reader = await documentCommand.ExecuteReaderAsync();
                if (!await reader.ReadAsync())
                    throw new BusinessRuleException($"Không tìm thấy tài liệu #{documentId}.");
                dossierId = reader.GetInt64(0);
                previousDocumentStatus = reader.GetString(1).Trim().ToUpperInvariant();
                ocrStatus = reader.GetString(2).Trim().ToUpperInvariant();
            }

            if (ocrStatus is not ("DONE" or "CONFIRMED"))
                throw new BusinessRuleException($"Tài liệu #{documentId} chưa OCR hoàn tất (OCR_STATUS={ocrStatus}).");

            string previousDossierStatus;
            await using (var dossierCommand = BuildCommand(connection, """
                SELECT NVL(STATUS, 'DRAFT')
                FROM DMS_DOSSIERS
                WHERE ID=:id
                FOR UPDATE
                """, P("id", dossierId)))
            {
                dossierCommand.Transaction = transaction;
                var value = await dossierCommand.ExecuteScalarAsync();
                if (value is null || value == DBNull.Value)
                    throw new BusinessRuleException($"Không tìm thấy hồ sơ #{dossierId} của tài liệu #{documentId}.");
                previousDossierStatus = Convert.ToString(value)?.Trim().ToUpperInvariant() ?? "DRAFT";
            }

            var documentStatus = ResolveOcrSubmissionStatus("Tài liệu", previousDocumentStatus);
            var dossierStatus = ResolveOcrSubmissionStatus("Hồ sơ", previousDossierStatus);
            await ExecuteInTransactionAsync(
                "UPDATE DMS_DOCUMENTS SET STATUS=:status, UPDATED_AT=SYSDATE WHERE ID=:id",
                P("status", documentStatus), P("id", documentId));
            await ExecuteInTransactionAsync(
                "UPDATE DMS_DOSSIERS SET STATUS=:status, UPDATED_AT=SYSDATE WHERE ID=:id",
                P("status", dossierStatus), P("id", dossierId));

            const string eventSql = """
                INSERT INTO DMS_WORKFLOW_EVENTS
                    (ENTITY_TYPE, ENTITY_ID, ACTION, FROM_STATUS, TO_STATUS, COMMENT_TEXT, ACTOR, UNIT_CODE)
                VALUES
                    (:entityType, :entityId, 'SUBMIT', :fromStatus, 'PENDING', :commentText, :actor, :unitCode)
                """;
            await ExecuteInTransactionAsync(eventSql,
                P("entityType", "DOCUMENT"), P("entityId", documentId),
                P("fromStatus", previousDocumentStatus),
                P("commentText", "Tự động gửi kiểm duyệt sau khi OCR và sinh PDF số hóa hoàn tất"),
                P("actor", actor), P("unitCode", unitCode));
            await ExecuteInTransactionAsync(eventSql,
                P("entityType", "DOSSIER"), P("entityId", dossierId),
                P("fromStatus", previousDossierStatus),
                P("commentText", $"Tự động gửi kiểm duyệt do tài liệu #{documentId} đã OCR hoàn tất"),
                P("actor", actor), P("unitCode", unitCode));

            await ExecuteInTransactionAsync("""
                INSERT INTO DMS_NOTIFICATIONS
                    (CODE, ENTITY_TYPE, ENTITY_ID, RECIPIENT, CHANNEL, TITLE, CONTENT_TEXT, STATUS, SENT_AT)
                VALUES
                    (:code, 'DOCUMENT', :entityId, :recipient, 'SYSTEM', :title, :contentText, 'SENT', SYSDATE)
                """,
                P("code", $"TB-OCR-{Guid.NewGuid():N}"),
